const INITIAL_BY_CHAR = new Map<string, string>()
for (const [initial, chars] of GROUPS) {
  for (const ch of chars) {
    // 后出现的分组不覆盖先出现的（同音字只会出现在一组里，此处仅作保险）
    if (!INITIAL_BY_CHAR.has(ch)) INITIAL_BY_CHAR.set(ch, initial)
  }
}

/**
 * 取一段文本的拼音首字母串（非汉字原样保留）。
 *
 * 例：`initialsOf('工作总结')` → `'gzzj'`；`initialsOf('工作')` → `'gz'`
 * 未收录的字会被跳过（不产生字母），因此结果可能短于原文 —— 调用方据此判断能否匹配。
 */
export function initialsOf(text: string): string {
  let out = ''
  for (const ch of text) {
    const initial = INITIAL_BY_CHAR.get(ch)
    if (initial) out += initial
    else if (/[a-z0-9]/i.test(ch)) out += ch.toLowerCase() // 英文数字原样参与（如「react 笔记」）
  }
  return out
}

/** 该文本是否至少含一个可识别的汉字（否则首字母匹配无意义，可直接跳过） */
export function hasKnownInitials(text: string): boolean {
  for (const ch of text) {
    if (INITIAL_BY_CHAR.has(ch)) return true
  }
  return false
}
