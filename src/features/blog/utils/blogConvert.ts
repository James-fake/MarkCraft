export interface ReadingTimeResult {
  minutes: number
  wordCount: number
  display: string
  displayZh: string
}

export function estimateReadingTime(html: string): ReadingTimeResult {
  const text = html.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim()
  const chineseChars = (text.match(/[\u4e00-\u9fff]/g) || []).length
  const englishWords = text.replace(/[\u4e00-\u9fff]/g, ' ').split(/\s+/).filter(w => w.length > 0).length
  const wordCount = chineseChars + englishWords
  const minutes = Math.max(1, Math.ceil(chineseChars / 300 + englishWords / 200))
  return {
    minutes,
    wordCount,
    display: `~${minutes} min read · ${wordCount} words`,
    displayZh: `约 ${minutes} 分钟 · ${wordCount} 字`,
  }
}

export function extractToc(html: string): Array<{ id: string; text: string; level: number; existingId?: string }> {
  const toc: Array<{ id: string; text: string; level: number; existingId?: string }> = []
  const regex = /<h([1-6])([^>]*)>([\s\S]*?)<\/h[1-6]>/g
  let match
  while ((match = regex.exec(html)) !== null) {
    const level = parseInt(match[1])
    const attrs = match[2]
    const text = match[3].replace(/<[^>]+>/g, '').trim()
    // Skip Footnotes heading generated by markedFootnote
    if (attrs.includes('sr-only') || attrs.includes('footnote-label')) continue
    const idMatch = attrs.match(/id="([^"]*)"/)
    const existingId = idMatch ? idMatch[1] : undefined
    const id = existingId || ('section-' + text.replace(/[^a-zA-Z0-9\u4e00-\u9fff]/g, '-').toLowerCase())
    toc.push({ id, text, level, existingId })
  }
  return toc
}
