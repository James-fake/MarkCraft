import { describe, it, expect, vi } from 'vitest'
import { syncCanvasLinks } from './syncCanvasLinks'
import type { CanvasEngine } from '../engine/CanvasEngine'
import type { FileNode } from '@src/types/fileManager'

/**
 * 回归锁（2026-11-03 穷尽式审查 P0-6）：
 * 期望边曾用 `${from}-${to}` 拼接、再 `lastIndexOf('-')` 反解 —— 而 shape id 由 genId
 * 生成形如 `shape-<base36>-<seq>`，**自身含连字符**，反解得到损坏 id →
 * createBoundArrow 找不到元素恒返回 null → 「同步笔记链接」只删不加，功能从未生效。
 * 现改为结构化 pair（from/to 单独存，key 用 NUL 分隔）。
 */
const T = 1700000000000

function makeCard(id: string, fileId: string) {
  return { id, type: 'note-card', props: { fileId } }
}

function makeTree(): FileNode {
  return {
    id: 'root',
    name: 'root',
    type: 'folder',
    createdAt: T,
    updatedAt: T,
    children: [
      { id: 'file-a', name: '笔记 A.md', type: 'file', content: '', createdAt: T, updatedAt: T },
      { id: 'file-b', name: '笔记 B.md', type: 'file', content: '', createdAt: T, updatedAt: T },
    ],
  }
}

function makeEngine(cards: ReturnType<typeof makeCard>[], arrows: unknown[] = []) {
  const createBoundArrow = vi.fn((from: string, to: string) => `arrow:${from}->${to}`)
  const engine = {
    getCurrentPageShapes: () => cards,
    excalidrawAPI: {
      getSceneElements: () => arrows,
      updateScene: vi.fn(),
    },
    createBoundArrow,
    deleteShapes: vi.fn(),
  } as unknown as CanvasEngine
  return { engine, createBoundArrow }
}

describe('P0-6 · 同步笔记链接：含连字符的 shape id 不得被反解撕碎', () => {
  it('createBoundArrow 收到完整 id（shape-<base36>-<seq> 形态）', async () => {
    // ⚠️ id 故意带连字符 —— 旧实现 lastIndexOf('-') 会把 from 切成 'shape-aaa-1-shape'
    const cards = [makeCard('shape-aaa-1', 'file-a'), makeCard('shape-bbb-2', 'file-b')]
    const { engine, createBoundArrow } = makeEngine(cards)

    const result = await syncCanvasLinks({
      engine,
      docId: 'doc-1',
      rootFolder: makeTree(),
      getOutgoingLinks: (fileId) =>
        fileId === 'file-a' ? [{ target: '笔记 B', relation: '支撑' }] : [],
    })

    expect(result.added).toBe(1)
    expect(createBoundArrow).toHaveBeenCalledTimes(1)
    expect(createBoundArrow).toHaveBeenCalledWith('shape-aaa-1', 'shape-bbb-2')
    // 反解损坏的形态绝不能出现
    const [from, to] = createBoundArrow.mock.calls[0]
    expect(from).not.toContain('shape-aaa-1-shape')
    expect(to).toBe('shape-bbb-2')
  })

  it('已存在的箭头不重复创建（结构化 key 与现有边匹配）', async () => {
    const cards = [makeCard('shape-aaa-1', 'file-a'), makeCard('shape-bbb-2', 'file-b')]
    const arrows = [
      { id: 'arrow-1', type: 'arrow', startBinding: { elementId: 'shape-aaa-1' }, endBinding: { elementId: 'shape-bbb-2' }, customData: { autoGenerated: true } },
    ]
    const { engine, createBoundArrow } = makeEngine(cards, arrows)

    const result = await syncCanvasLinks({
      engine,
      docId: 'doc-1',
      rootFolder: makeTree(),
      getOutgoingLinks: (fileId) => (fileId === 'file-a' ? [{ target: '笔记 B' }] : []),
    })

    expect(result.added).toBe(0)
    expect(result.removed).toBe(0)
    expect(createBoundArrow).not.toHaveBeenCalled()
  })

  it('不再期望的 autoGenerated 箭头被清理（结构 key 匹配后删除）', async () => {
    const cards = [makeCard('shape-aaa-1', 'file-a'), makeCard('shape-bbb-2', 'file-b')]
    const arrows = [
      { id: 'arrow-stale', type: 'arrow', startBinding: { elementId: 'shape-aaa-1' }, endBinding: { elementId: 'shape-bbb-2' }, customData: { autoGenerated: true } },
    ]
    const { engine } = makeEngine(cards, arrows)

    const result = await syncCanvasLinks({
      engine,
      docId: 'doc-1',
      rootFolder: makeTree(),
      // 出链已删除 → 期望边为空
      getOutgoingLinks: () => [],
    })

    expect(result.removed).toBe(1)
    expect(engine.deleteShapes).toHaveBeenCalledWith(['arrow-stale'])
  })
})
